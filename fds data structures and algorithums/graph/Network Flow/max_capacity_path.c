/*
 * 寻找最大容量路径的算法实现
    * 该算法使用了Dijkstra算法的变体来寻找从源点到目标点的最大容量路径。
    * 算法的核心思想是使用一个优先队列来维护当前路径的最大容量，并不断更新路径上的容量值。
    * 算法的时间复杂度为O(E log V)，其中E是图中的边数，V是图中的顶点数。
    * 算法的空间复杂度为O(V)，主要用于存储图的邻接矩阵和路径容量值。
    * 算法的输入包括图的顶点数、边数、源点和目标点，以及图的边信息。算法的输出是从源点到目标点的最大容量路径的容量值。
    * 算法的实现细节包括：
        1. 初始化图的邻接矩阵和路径容量值。
        2. 使用一个优先队列来维护当前路径的最大容量，并将源点加入队列。
        3. 在每次迭代中，从优先队列中取出当前路径容量最大的顶点，并更新其邻接顶点的路径容量值。
        4. 重复步骤3，直到目标点被访问或者优先队列为空。
        5. 返回目标点的路径容量值作为结果。
    * 该算法适用于寻找最大容量路径的问题，例如在网络流问题中寻找最大流量路径。
 */
